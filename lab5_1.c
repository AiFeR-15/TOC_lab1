#include <stdio.h>

int main() {
    int n, m;

    // 1. Зчитування кількості міст (2 <= n <= 100) та доріг (1 <= m <= 1000)
    while (1) {
        printf("Введіть кількість міст n (2..100) та кількість доріг m (1..1000): ");
        if (scanf("%d %d", &n, &m) != 2 || n < 2 || n > 100 || m < 1 || m > 1000) {
            printf("Помилка вводу! Перевірте межі значень.\n");
            while (getchar() != '\n');
            continue;
        }
        break;
    }

    // Матриця суміжності (індексуємо з 1 до n, щоб номери міст збігалися)
    int adj[101][101] = {0};

    // 2. Зчитування m двосторонніх доріг
    printf("Введіть %d пар міст (i j), з'єднаних дорогами:\n", m);
    for (int k = 0; k < m; k++) {
        int u, v;
        if (scanf("%d %d", &u, &v) != 2 || u < 1 || u > n || v < 1 || v > n) {
            printf("Помилка! Номери міст мають бути від 1 до %d. Повторіть дорогу #%d: ", n, k + 1);
            while (getchar() != '\n');
            k--;
            continue;
        }
        adj[u][v] = 1;
        adj[v][u] = 1; // Дорога двостороння
    }

    // 3. Зчитування стартового міста st
    int st;
    while (1) {
        printf("Введіть номер міста спалаху інфекції st (1..%d): ", n);
        if (scanf("%d", &st) != 1 || st < 1 || st > n) {
            printf("Помилка! Введіть число від 1 до %d.\n", n);
            while (getchar() != '\n');
            continue;
        }
        break;
    }

    // 4. Підготовка масиву днів та черги для пошуку в ширину (BFS)
    int days[101];
    for (int i = 1; i <= n; i++) {
        days[i] = -1; // -1 означає, що місто ще не заражене
    }

    int queue[101];
    int head = 0; // "Голова" черги (поточне місто)
    int tail = 0; // "Хвіст" черги (місце для додавання нових міст)

    // Починаємо зі стартового міста
    days[st] = 0;
    queue[tail++] = st;

    // 5. Основний цикл пошуку в ширину
    while (head < tail) {
        int current = queue[head++]; // Беремо місто з голови черги

        // Переглядаємо всі міста, щоб знайти сусідів current
        for (int next = 1; next <= n; next++) {
            // Якщо є дорога (adj == 1) і місто ще не заражене (days == -1)
            if (adj[current][next] == 1 && days[next] == -1) {
                days[next] = days[current] + 1; // Заражається на наступний день
                queue[tail++] = next;           // Додаємо в хвіст черги
            }
        }
    }

    // 6. Аналіз результатів
    int max_days = 0;
    for (int i = 1; i <= n; i++) {
        if (days[i] == -1) {
            // Якщо хоча б одне місто залишилося не зараженим (граф незв'язний)
            printf("\nРезультат: -1 (не всі міста будуть заражені)\n");
            return 0;
        }
        if (days[i] > max_days) {
            max_days = days[i];
        }
    }

    printf("\nРезультат: %d дн. (через стільки днів заразяться всі міста)\n", max_days);

    return 0;
}